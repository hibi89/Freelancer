"""Non-destructive Windows 10/11 local acceptance drill for WORKNOVA Desk.

Run only on Windows with Python >=3.11 and Tk. No admin, network, policy bypass,
existing customer data access, real profile writes or external package installation.
All installation artifacts live in a newly created disposable TEMP directory;
PowerShell receives a throwaway LOCALAPPDATA environment just for this process.

This tests packaging/installation/upgrade/rollback by PowerShell and GUI window
creation, NOT code signing, Defender reputation, commercial buyer acceptance,
BitLocker/ACL policy, licensed Word rendering or actual human ergonomics.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Running py -3 tools/windows_acceptance.py sets sys.path to tools/, not repo root.
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


def _ok(result: str, detail: str = '') -> dict:
    return {'check': result, 'status': 'PASS', 'detail': detail}


def _run(command: list[str], *, cwd: Path, env: dict[str, str], label: str) -> None:
    result = subprocess.run(command, cwd=str(cwd), env=env, text=True,
                            capture_output=True, timeout=100, check=False)
    if result.returncode != 0:
        # Tool output could contain file paths or private user data: avoid echoing.
        raise RuntimeError(f'{label}: process exited {result.returncode}; inspect local console in a private environment')


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _accept() -> list[dict]:
    if sys.platform != 'win32':
        raise RuntimeError('Native Windows required. Linux/Powershell simulation is not Windows acceptance.')
    if sys.version_info < (3, 11):
        raise RuntimeError('Python 3.11 or later required')
    powershell = shutil.which('powershell.exe') or shutil.which('powershell')
    if not powershell:
        raise RuntimeError('Windows PowerShell executable not found')
    if not (ROOT/'scripts/install_local.ps1').is_file():
        raise RuntimeError('Run the script inside the WORKNOVA source checkout')

    # Create real Tk widgets. Do not claim UI usability or manual approval here.
    import tkinter as tk
    from tkinter import ttk
    main = tk.Tk()
    try:
        main.withdraw()
        label = ttk.Label(main, text='WORKNOVA Desk 합성 테스트')
        label.pack()
        main.update_idletasks()
        if 'WORKNOVA' not in label.cget('text'):
            raise RuntimeError('Tk GUI smoke mismatch')
    finally:
        main.destroy()
    checks = [_ok('Windows Python + Tk window')]

    # TEMP is generated by the OS; all installed paths and scratch DBs are below it.
    with tempfile.TemporaryDirectory(prefix='worknova-qa-') as temporary:
        work = Path(temporary)
        profile = work/'disposable_LOCALAPPDATA'
        profile.mkdir(mode=0o700)
        env = os.environ.copy()
        env['LOCALAPPDATA'] = str(profile)
        env['PYTHONPYCACHEPREFIX'] = str(work/'pycache')
        package_zip = work/'offline-source.zip'
        source = work/'source'
        source.mkdir()
        from scripts.build_portable import bundle
        from scripts.verify_portable import PackageError, verify
        bundle(ROOT, package_zip)
        with zipfile.ZipFile(package_zip) as z:
            for name in z.namelist():
                if name.startswith('/') or '..' in Path(name).parts:
                    raise RuntimeError('Unsafe ZIP member')
            z.extractall(source)
        report = verify(source)
        checks.append(_ok('Portable ZIP extraction and allowlist', str(report['verified_files'])))
        verify_script = source/'verify_portable.py'
        _run([sys.executable, '-B', str(verify_script), '--root', str(source)],
             cwd=source, env=env, label='Preinstall integrity')
        checks.append(_ok('Portable command preflight'))

        script = source/'install_local.ps1'
        # No -ExecutionPolicy Bypass and no parent-process environment changes.
        def install(*flags: str):
            _run([powershell, '-NoProfile', '-NonInteractive', '-File', str(script), *flags],
                 cwd=source, env=env, label='PowerShell ' + ','.join(flags or ('install',)))

        install('-DryRun')
        checks.append(_ok('PowerShell no-change dry run'))
        install()
        app = profile/'Programs'/'WORKNOVA Desk'/'app'
        installed = verify(app)
        if installed['verified_files'] != report['verified_files']:
            raise RuntimeError('Installed manifest mismatch')
        checks.append(_ok('PowerShell per-user install in disposable profile'))

        datadir = profile/'WORKNOVA Desk'/'Data'
        db = datadir/'synthetic.sqlite'
        _run([sys.executable, '-B', '-m', 'worknova_desk', '--db', str(db), 'init'],
             cwd=app, env=env, label='New synthetic ledger')
        _run([sys.executable, '-B', '-m', 'worknova_desk', '--db', str(db), 'customer',
              '--name', '합성 샘플 회사'], cwd=app, env=env, label='Synthetic customer')
        _run([sys.executable, '-B', '-m', 'worknova_desk', '--db', str(db), 'verify'],
             cwd=app, env=env, label='Synthetic ledger integrity')
        protected_digest = _sha(db)
        checks.append(_ok('Synthetic ledger and audit verification'))
        # Optional backup encryption. If dependency absent, report SKIP rather than PASS.
        try:
            import cryptography
        except ImportError:
            checks.append({'check': 'AES-GCM encrypted backup/restore', 'status': 'SKIP',
                           'detail': 'optional local cryptography not installed'})
        else:
            from worknova_desk.core import Desk
            from worknova_desk.secure_backup import encrypted_backup, encrypted_restore_new
            sealed = work/'synthetic-encrypted.wndesk'
            decrypted = work/'synthetic-decrypted.sqlite'
            live=Desk(db,allow_create=False)
            try:
                token=encrypted_backup(live,sealed,'synthetic-throwaway-secret-1234')
            finally:
                live.close()
            encrypted_restore_new(sealed,decrypted,'synthetic-throwaway-secret-1234',
                                  expected_sha256=token['sha256'])
            if _sha(db) != protected_digest:
                raise RuntimeError('Encrypted roundtrip changed synthetic source ledger')
            decrypted_db=Desk(decrypted,allow_create=False)
            try:
                if decrypted_db.verify_audit() < 1:
                    raise RuntimeError('Encrypted roundtrip lost synthetic audit')
            finally:
                decrypted_db.close()
            checks.append(_ok('AES-GCM encrypted backup/restore, temporary fixture only'))

        scratch = work/'recovery-scratch'
        scratch.mkdir(mode=0o700)
        _run([sys.executable, '-B', '-m', 'worknova_desk', '--db', str(db), 'rehearse-restore',
              '--workspace-dir', str(scratch)], cwd=app, env=env,
             label='Synthetic backup restore drill')
        if _sha(db) != protected_digest:
            raise RuntimeError('Restore rehearsal modified original synthetic ledger')
        checks.append(_ok('Synthetic backup/restore preserves original'))

        install()
        verify(app)
        if _sha(db) != protected_digest:
            raise RuntimeError('Upgrade modified synthetic ledger')
        previous = list((profile/'Programs'/'WORKNOVA Desk').glob('.previous-*'))
        if len(previous) != 1:
            raise RuntimeError('Exactly one rollback app candidate was not retained')
        verify(previous[0])
        checks.append(_ok('PowerShell upgrade/rollback app and data preservation'))

        install('-Uninstall', '-ConfirmRemoveApp')
        if app.exists() or not db.is_file() or _sha(db) != protected_digest:
            raise RuntimeError('Uninstall deleted application incorrectly or changed data')
        checks.append(_ok('PowerShell app-only uninstall retains synthetic DB'))
    # Python TemporaryDirectory removes all disposable data and app artifacts.
    checks.append(_ok('Disposable profile and synthetic files cleaned'))
    return checks


def main() -> int:
    try:
        checks = _accept()
        print(json.dumps({'ok': True, 'platform': sys.platform,
                          'checks': checks, 'scope': 'native Windows synthetic offline QA only'},
                         ensure_ascii=False, sort_keys=True))
        return 0
    except Exception as error:
        # Deliberately avoid stacktraces, host paths and customer data in summary.
        print(json.dumps({'ok': False, 'platform': sys.platform,
                          'error': type(error).__name__ + ': ' + str(error),
                          'scope': 'Windows acceptance NOT confirmed'},
                         ensure_ascii=False, sort_keys=True))
        return 3


if __name__ == '__main__':
    raise SystemExit(main())
